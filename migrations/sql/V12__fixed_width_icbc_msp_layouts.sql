  a.old_street_name,
  a.old_street_type,
  a.old_street_direction,
  a.old_city,
  a.old_province,
  a.old_postal_code,
  a.old_address_line_one,
  a.old_address_line_two,
  a.old_country,
  a.new_address_flag,
  a.new_unit_number,
  a.new_street_number,
  a.new_street_suffix,
  a.new_street_name,
  a.new_street_type,
  a.new_street_direction,
  a.new_city,
  a.new_province,
  a.new_postal_code,
  a.new_address_line_one,
  a.new_address_line_two,
  a.new_country,
  p.daytime_phone,
  p.email_address,
  a.mailing_address_flag,
  a.mailing_unit_number,
  a.mailing_street_number,
  a.mailing_street_suffix,
  a.mailing_street_name,
  a.mailing_street_type,
  a.mailing_street_direction,
  a.mailing_city,
  a.mailing_province,
  a.mailing_postal_code,
  a.mailing_address_line_one,
  a.mailing_address_line_two,
  a.mailing_country,
  p.drivers_license_number_encrypted AS drivers_license_number,
  p.height_cm,
  p.weight_kg,
  p.security_keyword_encrypted AS security_keyword,
  p.phn_encrypted AS phn,
  a.is_mailing_address_same,
  NULL::text AS old_po_box,
  NULL::text AS old_postal_station,
  NULL::text AS old_site,
  NULL::text AS old_compartment,
  NULL::text AS old_route,
  NULL::text AS new_po_box,
  NULL::text AS new_postal_station,
  NULL::text AS new_site,
  NULL::text AS new_compartment,
  NULL::text AS new_route,
  NULL::text AS mailing_po_box,
  NULL::text AS mailing_postal_station,
  NULL::text AS mailing_site,
  NULL::text AS mailing_compartment,
  NULL::text AS mailing_route
FROM address_change.address_change_request r
JOIN address_change.request_person p USING (request_id)
JOIN address_change.submitted_address a USING (request_id);

